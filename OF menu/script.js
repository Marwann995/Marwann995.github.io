function renderMenu(filterText = '') {
    menuStage.innerHTML = '';

    menuData.forEach((cat, catIdx) => {
        const filteredItems = cat.items.filter(item => 
            item.name.toLowerCase().includes(filterText.toLowerCase()) ||
            (item.desc && item.desc.toLowerCase().includes(filterText.toLowerCase()))
        );

        if (filteredItems.length === 0 && filterText !== '') return;

        const catBlock = document.createElement('div');
        catBlock.className = 'category-block';
        catBlock.id = `cat-${catIdx}`;

        let itemsHTML = filteredItems.map((item, itemIdx) => {
            const realItemIdx = cat.items.indexOf(item);
            return `
                <div class="menu-card">
                    ${item.image ? `<img src="${item.image}" class="item-img" alt="${item.name}" loading="lazy">` : ''}
                    <div class="card-content">
                        <div class="card-top">
                            <div class="item-name">${item.name}</div>
                            <div class="item-price">${item.price}</div>
                        </div>
                        ${item.desc ? `<div class="item-desc">${item.desc}</div>` : ''}
                    </div>
                    ${isAdminMode ? `
                        <div class="admin-controls">
                            <button class="btn-inline-edit" onclick="openEditModal(${catIdx}, ${realItemIdx})">
                                <i class="fa-solid fa-pen-to-square"></i> تعديل
                            </button>
                            <button class="btn-inline-del" onclick="deleteItem(${catIdx}, ${realItemIdx})">
                                <i class="fa-solid fa-trash"></i> حذف
                            </button>
                        </div>
                    ` : ''}
                </div>
            `;
        }).join('');

        const categoryIcon = cat.icon || 'fa-solid fa-utensils';

        // Render Addons Badges HTML
        let addonsHTML = '';
        if (cat.addons && cat.addons.length > 0) {
            addonsHTML = `
                <div class="category-addons-wrap">
                    ${cat.addons.map(addon => `
                        <div class="category-addon-badge">
                            <i class="fa-solid fa-circle-plus"></i> ${addon}
                        </div>
                    `).join('')}
                </div>
            `;
        }

        catBlock.innerHTML = `
            ${cat.image ? `
                <div class="category-banner" style="background-image: linear-gradient(rgba(0,0,0,0.55), rgba(0,0,0,0.55)), url('${cat.image}');">
                    <h2 class="category-title">
                        <i class="${categoryIcon} category-icon"></i>
                        ${cat.category}
                    </h2>
                </div>
            ` : `
                <div class="category-header-wrap">
                    <h2 class="category-title">
                        <i class="${categoryIcon} category-icon"></i>
                        ${cat.category}
                    </h2>
                    ${isAdminMode ? `
                        <button class="btn-add-item" onclick="openAddModal(${catIdx})">
                            <i class="fa-solid fa-plus"></i> إضافة عنصر
                        </button>
                    ` : ''}
                </div>
            `}
            ${addonsHTML}
            <div class="items-grid">${itemsHTML}</div>
        `;

        menuStage.appendChild(catBlock);
        
    });
    
    // Re-attach observer whenever menu renders or updates
    setTimeout(() => setupScrollObserver(), 100);
}

// Category Slider & Drawer List Render
function renderCategories() {
    categoryStrip.innerHTML = '';
    drawerCatList.innerHTML = '';

    menuData.forEach((cat, idx) => {
        const catId = `cat-${idx}`;
        const chipIcon = cat.icon ? `<i class="${cat.icon}"></i> ` : '';

        // Category bar chip
        const chip = document.createElement('button');
        chip.className = `cat-chip ${idx === 0 ? 'active' : ''}`;
        chip.setAttribute('data-target', catId);
        chip.innerHTML = `${chipIcon}${cat.category}`;
        chip.onclick = () => {
            const targetEl = document.getElementById(catId);
            if (targetEl) {
                targetEl.scrollIntoView({ behavior: 'smooth' });
            }
        };
        categoryStrip.appendChild(chip);

        // Sidebar link
        const li = document.createElement('li');
        li.innerHTML = `<a href="#${catId}">${chipIcon}${cat.category}</a>`;
        li.onclick = () => {
            if (typeof closeSidebarDrawer === 'function') {
                closeSidebarDrawer();
            }
        };
        drawerCatList.appendChild(li);
    });

    // Initialize scroll tracking after categories are rendered
    setupScrollObserver();
}

function scrollToCategory(id) {
    const el = document.getElementById(id);
    if (el) {
        const offset = 140;
        const bodyRect = document.body.getBoundingClientRect().top;
        const elementRect = el.getBoundingClientRect().top;
        const elementPosition = elementRect - bodyRect;
        const offsetPosition = elementPosition - offset;

        window.scrollTo({
            top: offsetPosition,
            behavior: 'smooth'
        });
    }
}

