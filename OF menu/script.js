// Automatically sync active category with scrolling position
let observer;

function setupScrollObserver() {
    if (observer) observer.disconnect();

    const options = {
        root: null,
        rootMargin: '-20% 0px -70% 0px', // Triggers when category enters upper portion of viewport
        threshold: 0
    };

    observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                const catId = entry.target.id;
                
                // Highlight active chip in horizontal category bar
                const chips = document.querySelectorAll('.cat-chip');
                chips.forEach((chip) => {
                    const isTarget = chip.getAttribute('data-target') === catId;
                    chip.classList.toggle('active', isTarget);
                    
                    if (isTarget) {
                        chip.scrollIntoView({ behavior: 'smooth', block: 'nearest', inline: 'center' });
                    }
                });

                // Highlight active link in sidebar drawer
                const drawerLinks = document.querySelectorAll('#drawerCatList a');
                drawerLinks.forEach(link => {
                    const isTarget = link.getAttribute('href') === `#${catId}`;
                    link.classList.toggle('active', isTarget);
                });
            }
        });
    }, options);

    document.querySelectorAll('.category-block').forEach(block => {
        observer.observe(block);
    });
}